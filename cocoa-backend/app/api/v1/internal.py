"""Internal endpoints used by agent pods running in K8s mode.

These endpoints are NOT exposed publicly — they are only callable from
agent pods (or trusted local processes) that present the shared
``COCOA_API_TOKEN``. The token is generated by the backend lifespan on
startup and injected into instance pods by DeployService (P11c Todo 1).

Two surfaces:

* ``POST /api/v1/internal/events/emit`` — agent pod persists an audit
  event via the in-process :func:`app.core.events.emit` pipeline, which
  also fires the registered best-effort handlers.
* ``GET  /api/v1/internal/control/poll`` — agent pod polls the D11
  control-plane downlink (``harness.control_sent`` events) for its own
  ``instance_id``.

Both endpoints are gated by :func:`verify_internal_token`, which compares
the request's ``Authorization: Bearer <token>`` header against the
``COCOA_API_TOKEN`` environment variable using
:func:`secrets.compare_digest` (timing-safe).
"""

